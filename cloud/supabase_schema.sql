-- Run in Supabase SQL Editor for the cloud database version.
create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text unique not null,
  role text not null check (role in ('student','teacher')),
  created_at timestamptz default now()
);

create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  course_name text not null,
  teacher_id bigint references public.users(id) on delete cascade,
  created_at timestamptz default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  course_id bigint references public.courses(id) on delete cascade,
  title text not null,
  description text default '',
  deadline timestamptz not null,
  max_marks integer not null check (max_marks > 0),
  allowed_file_types text default 'pdf,docx,txt',
  max_file_size_mb integer default 10,
  created_by bigint references public.users(id) on delete cascade,
  created_at timestamptz default now()
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint references public.assignments(id) on delete cascade,
  student_id bigint references public.users(id) on delete cascade,
  file_name text not null,
  file_url text,
  storage_path text not null,
  submitted_at timestamptz default now(),
  submission_status text default 'SUBMITTED',
  marks integer,
  feedback text,
  graded_at timestamptz
);

create index if not exists idx_assignments_deadline on public.assignments(deadline);
create index if not exists idx_submissions_student on public.submissions(student_id);
create index if not exists idx_submissions_assignment on public.submissions(assignment_id);

